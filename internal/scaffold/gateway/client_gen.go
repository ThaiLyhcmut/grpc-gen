package gateway

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"
)

// ClientGenInput drives generation of graph/client/*.go.
type ClientGenInput struct {
	ServerDir  string // e.g. "src/server"
	ModulePath string // user module
	Protos     []ProtoInfo
}

// GenerateClients writes graph/client/<service>.go per service + a
// graph/client/clients.go aggregator + graph/client/cache_helpers.go that
// owns the proto-marshal-based serialisation and viewer-id extraction
// used by every per-service cache wrap.
func GenerateClients(in ClientGenInput) error {
	dir := filepath.Join(in.ServerDir, "graph", "client")
	if err := os.MkdirAll(dir, 0755); err != nil {
		return err
	}

	for _, p := range in.Protos {
		content := renderClientFile(p, in.ModulePath)
		path := filepath.Join(dir, p.ServiceName+".go")
		if err := os.WriteFile(path, []byte(content), 0644); err != nil {
			return err
		}
	}

	agg := renderClientsAggregator(in.Protos, in.ModulePath)
	if err := os.WriteFile(filepath.Join(dir, "clients.go"), []byte(agg), 0644); err != nil {
		return err
	}

	helpers := renderClientCacheHelpers(in.ModulePath)
	if err := os.WriteFile(filepath.Join(dir, "cache_helpers.go"), []byte(helpers), 0644); err != nil {
		return err
	}

	return nil
}

// rpcOp returns (op, entity) by stripping the matching prefix from name.
// Returns empty op when the RPC doesn't follow the <Op><Entity> convention.
func rpcOp(name string) (op, entity string) {
	for _, p := range []string{"Create", "Update", "Delete", "List"} {
		if strings.HasPrefix(name, p) {
			return p, strings.TrimPrefix(name, p)
		}
	}
	return "", ""
}

func renderClientFile(p ProtoInfo, modulePath string) string {
	var sb strings.Builder
	clientStruct := capitalize(p.ServiceName) + "Client"

	fmt.Fprintf(&sb, "// Code generated by grpc-gen. DO NOT EDIT.\n")
	fmt.Fprintf(&sb, "// gRPC client wrapper for the %s service (with cache layer).\n\n", p.ServiceName)
	fmt.Fprintf(&sb, "package client\n\n")

	fmt.Fprintf(&sb, "import (\n")
	fmt.Fprintf(&sb, "\t\"context\"\n")
	fmt.Fprintf(&sb, "\t\"time\"\n\n")
	fmt.Fprintf(&sb, "\t\"google.golang.org/grpc\"\n")
	fmt.Fprintf(&sb, "\t\"google.golang.org/protobuf/proto\"\n\n")
	fmt.Fprintf(&sb, "\tpb \"%s/proto/%s\"\n", modulePath, p.ServiceName)
	fmt.Fprintf(&sb, "\t\"%s/src/server/graph/cache\"\n", modulePath)
	fmt.Fprintf(&sb, ")\n\n")

	// Struct.
	fmt.Fprintf(&sb, "type %s struct {\n", clientStruct)
	fmt.Fprintf(&sb, "\tconn  *grpc.ClientConn\n")
	fmt.Fprintf(&sb, "\tstub  pb.%sServiceClient\n", capitalize(p.ServiceName))
	fmt.Fprintf(&sb, "\tcache cache.Cache\n")
	fmt.Fprintf(&sb, "\tttl   time.Duration\n")
	fmt.Fprintf(&sb, "}\n\n")

	// Constructor.
	fmt.Fprintf(&sb, "func New%s(addr string, ca cache.Cache, ttl time.Duration, opts ...grpc.DialOption) (*%s, error) {\n", clientStruct, clientStruct)
	fmt.Fprintf(&sb, "\tconn, err := grpc.NewClient(addr, opts...)\n")
	fmt.Fprintf(&sb, "\tif err != nil { return nil, err }\n")
	fmt.Fprintf(&sb, "\treturn &%s{conn: conn, stub: pb.New%sServiceClient(conn), cache: ca, ttl: ttl}, nil\n", clientStruct, capitalize(p.ServiceName))
	fmt.Fprintf(&sb, "}\n\n")

	// Close + Stub passthrough.
	fmt.Fprintf(&sb, "func (c *%s) Close() error { return c.conn.Close() }\n", clientStruct)
	fmt.Fprintf(&sb, "func (c *%s) Stub() pb.%sServiceClient { return c.stub }\n\n", clientStruct, capitalize(p.ServiceName))

	// Per-RPC methods.
	for _, rpc := range p.RPCs {
		op, entity := rpcOp(rpc.Name)
		switch op {
		case "List":
			writeListMethod(&sb, clientStruct, rpc, entity)
		case "Create", "Update", "Delete":
			writeMutateMethod(&sb, clientStruct, rpc, entity)
		default:
			// Unknown convention — passthrough so we don't break custom RPCs.
			fmt.Fprintf(&sb, "func (c *%s) %s(ctx context.Context, in *pb.%s, opts ...grpc.CallOption) (*pb.%s, error) {\n",
				clientStruct, rpc.Name, rpc.RequestType, rpc.ResponseType)
			fmt.Fprintf(&sb, "\treturn c.stub.%s(ctx, in, opts...)\n}\n\n", rpc.Name)
		}
	}

	return sb.String()
}

// writeListMethod emits a ListX method that checks the list cache (keyed by
// viewer + deterministic hash of the request) before calling gRPC.
func writeListMethod(sb *strings.Builder, clientStruct string, rpc RPCInfo, entity string) {
	fmt.Fprintf(sb, "func (c *%s) %s(ctx context.Context, in *pb.%s, opts ...grpc.CallOption) (*pb.%s, error) {\n",
		clientStruct, rpc.Name, rpc.RequestType, rpc.ResponseType)
	fmt.Fprintf(sb, "\tif c.cache == nil { return c.stub.%s(ctx, in, opts...) }\n", rpc.Name)
	fmt.Fprintf(sb, "\treqBytes, mErr := proto.MarshalOptions{Deterministic: true}.Marshal(in)\n")
	fmt.Fprintf(sb, "\tif mErr != nil { return c.stub.%s(ctx, in, opts...) }\n", rpc.Name)
	fmt.Fprintf(sb, "\tkey := cache.ListKey(%q, viewerID(ctx), cache.HashBytes(reqBytes))\n", entity)
	fmt.Fprintf(sb, "\tif b, ok, _ := c.cache.Get(ctx, key); ok {\n")
	fmt.Fprintf(sb, "\t\tvar cached pb.%s\n", rpc.ResponseType)
	fmt.Fprintf(sb, "\t\tif proto.Unmarshal(b, &cached) == nil { return &cached, nil }\n")
	fmt.Fprintf(sb, "\t}\n")
	fmt.Fprintf(sb, "\tresp, err := c.stub.%s(ctx, in, opts...)\n", rpc.Name)
	fmt.Fprintf(sb, "\tif err != nil { return nil, err }\n")
	fmt.Fprintf(sb, "\tif b, mErr := proto.Marshal(resp); mErr == nil { _ = c.cache.Set(ctx, key, b, c.ttl) }\n")
	fmt.Fprintf(sb, "\treturn resp, nil\n}\n\n")
}

// writeMutateMethod emits a Create/Update/Delete that passes through to gRPC
// and, on success, evicts every per-viewer key (id + list) for the entity.
func writeMutateMethod(sb *strings.Builder, clientStruct string, rpc RPCInfo, entity string) {
	fmt.Fprintf(sb, "func (c *%s) %s(ctx context.Context, in *pb.%s, opts ...grpc.CallOption) (*pb.%s, error) {\n",
		clientStruct, rpc.Name, rpc.RequestType, rpc.ResponseType)
	fmt.Fprintf(sb, "\tresp, err := c.stub.%s(ctx, in, opts...)\n", rpc.Name)
	fmt.Fprintf(sb, "\tif err == nil && c.cache != nil {\n")
	fmt.Fprintf(sb, "\t\t_ = c.cache.DelByPattern(ctx, \"e:%s:v:*\")\n", entity)
	fmt.Fprintf(sb, "\t}\n")
	fmt.Fprintf(sb, "\treturn resp, err\n}\n\n")
}

func renderClientsAggregator(protos []ProtoInfo, modulePath string) string {
	var sb strings.Builder

	sb.WriteString("// Code generated by grpc-gen. DO NOT EDIT.\n")
	sb.WriteString("// Aggregates per-service clients + their shared cache backend.\n\n")
	sb.WriteString("package client\n\n")

	sb.WriteString("import (\n")
	sb.WriteString("\t\"fmt\"\n")
	sb.WriteString("\t\"time\"\n\n")
	sb.WriteString("\t\"google.golang.org/grpc\"\n\n")
	fmt.Fprintf(&sb, "\t\"%s/src/server/graph/cache\"\n", modulePath)
	sb.WriteString(")\n\n")

	sb.WriteString("// Endpoints lists the dial address of each gRPC service.\n")
	sb.WriteString("type Endpoints struct {\n")
	for _, p := range protos {
		fmt.Fprintf(&sb, "\t%s string\n", capitalize(p.ServiceName))
	}
	sb.WriteString("}\n\n")

	sb.WriteString("type Clients struct {\n")
	sb.WriteString("\tCache cache.Cache\n")
	sb.WriteString("\tTTL   time.Duration\n")
	for _, p := range protos {
		fmt.Fprintf(&sb, "\t%s *%sClient\n", capitalize(p.ServiceName), capitalize(p.ServiceName))
	}
	sb.WriteString("}\n\n")

	sb.WriteString("// NewClients dials every service and shares the same Cache + TTL across\n")
	sb.WriteString("// them. Pass cache.Noop{} (or any zero ttl) to disable caching.\n")
	sb.WriteString("func NewClients(ep Endpoints, ca cache.Cache, ttl time.Duration, opts ...grpc.DialOption) (*Clients, error) {\n")
	sb.WriteString("\tif ca == nil { ca = cache.Noop{} }\n")
	sb.WriteString("\tc := &Clients{Cache: ca, TTL: ttl}\n")
	sb.WriteString("\tvar err error\n\n")
	for _, p := range protos {
		fmt.Fprintf(&sb, "\tif c.%s, err = New%sClient(ep.%s, ca, ttl, opts...); err != nil {\n", capitalize(p.ServiceName), capitalize(p.ServiceName), capitalize(p.ServiceName))
		fmt.Fprintf(&sb, "\t\tc.Close()\n")
		fmt.Fprintf(&sb, "\t\treturn nil, fmt.Errorf(\"dial %s: %%w\", err)\n", p.ServiceName)
		fmt.Fprintf(&sb, "\t}\n")
	}
	sb.WriteString("\treturn c, nil\n")
	sb.WriteString("}\n\n")

	sb.WriteString("func (c *Clients) Close() error {\n")
	sb.WriteString("\tvar firstErr error\n")
	for _, p := range protos {
		fmt.Fprintf(&sb, "\tif c.%s != nil {\n", capitalize(p.ServiceName))
		fmt.Fprintf(&sb, "\t\tif err := c.%s.Close(); err != nil && firstErr == nil { firstErr = err }\n", capitalize(p.ServiceName))
		fmt.Fprintf(&sb, "\t}\n")
	}
	sb.WriteString("\treturn firstErr\n}\n")

	return sb.String()
}

// renderClientCacheHelpers writes viewer-id extraction so the per-service
// files can build per-viewer cache keys without importing auth themselves.
func renderClientCacheHelpers(modulePath string) string {
	var sb strings.Builder
	sb.WriteString("// Code generated by grpc-gen. DO NOT EDIT.\n")
	sb.WriteString("// Shared helpers used by every per-service cache wrap.\n\n")
	sb.WriteString("package client\n\n")
	fmt.Fprintf(&sb, "import (\n")
	fmt.Fprintf(&sb, "\t\"context\"\n\n")
	fmt.Fprintf(&sb, "\t\"%s/src/server/graph/auth\"\n", modulePath)
	fmt.Fprintf(&sb, ")\n\n")
	sb.WriteString("// viewerID returns the request's user id, or cache.ViewerAnon for\n")
	sb.WriteString("// anonymous traffic. Lives here so the per-service files don't have to\n")
	sb.WriteString("// import auth themselves.\n")
	sb.WriteString("func viewerID(ctx context.Context) string {\n")
	sb.WriteString("\tv := auth.FromContext(ctx)\n")
	sb.WriteString("\tif v == nil { return \"\" }\n")
	sb.WriteString("\treturn v.UserID\n")
	sb.WriteString("}\n")
	return sb.String()
}

func capitalize(s string) string {
	if s == "" {
		return s
	}
	return strings.ToUpper(s[:1]) + s[1:]
}
