package gateway

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"
)

// DirectiveGenInput drives gen of graph/auth + graph/policy + graph/directive.
type DirectiveGenInput struct {
	ServerDir  string
	ModulePath string
}

// GenerateDirectives writes:
//   - graph/auth/viewer.go        — Viewer struct + ctx helpers (request identity)
//   - graph/policy/enforcer.go    — Enforcer interface the gateway depends on;
//     main.go wires a concrete impl (Casbin + Mongo, or "deny all" for dev).
//   - graph/directive/directive.go — runners for @auth and @policy that gqlgen
//     calls during field resolution.
func GenerateDirectives(in DirectiveGenInput) error {
	if err := writeViewer(in); err != nil {
		return err
	}
	if err := writeEnforcer(in); err != nil {
		return err
	}
	if err := writeDirectiveRunners(in); err != nil {
		return err
	}
	return nil
}

func writeViewer(in DirectiveGenInput) error {
	dir := filepath.Join(in.ServerDir, "graph", "auth")
	if err := os.MkdirAll(dir, 0755); err != nil {
		return err
	}
	body := strings.TrimLeft(`
// Code generated by grpc-gen. DO NOT EDIT.
// Viewer = the authenticated principal attached to a request. Populated by
// HTTP middleware in main.go (typically by decoding a JWT) and read by the
// directive runners + policy.Enforcer impls.

package auth

import "context"

// Viewer is the principal making this GraphQL request. UserID may be empty
// for anonymous traffic; Role is the canonical role string the policy engine
// matches against.
type Viewer struct {
	UserID string
	Role   string
	// Extra is open-ended ABAC scope: tenant id, organisation id, feature
	// flags, etc. Directive runners forward this verbatim to the enforcer.
	Extra map[string]any
}

type ctxKey struct{}

// WithViewer attaches v to ctx for downstream resolvers/directives.
func WithViewer(ctx context.Context, v *Viewer) context.Context {
	return context.WithValue(ctx, ctxKey{}, v)
}

// FromContext returns the viewer, or nil for anonymous requests.
func FromContext(ctx context.Context) *Viewer {
	v, _ := ctx.Value(ctxKey{}).(*Viewer)
	return v
}
`, "\n")
	return os.WriteFile(filepath.Join(dir, "viewer.go"), []byte(body), 0644)
}

func writeEnforcer(in DirectiveGenInput) error {
	dir := filepath.Join(in.ServerDir, "graph", "policy")
	if err := os.MkdirAll(dir, 0755); err != nil {
		return err
	}
	body := strings.TrimLeft(fmt.Sprintf(`
// Code generated by grpc-gen. DO NOT EDIT.
// Enforcer is the abstraction the @auth/@policy directives call into.
// main.go is expected to wire a real impl (e.g. Casbin reading from the
// policy-engine MongoDB collection). DenyAll is the safe default.

package policy

import (
	"context"
	"errors"

	"%s/src/server/graph/auth"
)

// ErrUnauthenticated and ErrForbidden are the two failure modes resolvers
// surface to clients. Wrap them with %%w if you need more detail.
var (
	ErrUnauthenticated = errors.New("unauthenticated")
	ErrForbidden       = errors.New("forbidden")
)

// Enforcer is the seam between directives and the actual policy backend.
// Implementations live in main.go (or a separate package the user owns).
type Enforcer interface {
	// HasRole returns true if viewer carries the given role string. nil
	// viewer means anonymous and should return false for every role.
	HasRole(ctx context.Context, v *auth.Viewer, role string) bool

	// EvalRule runs a named expression against the binding map. obj is the
	// parent GraphQL object (may be nil for top-level fields); extras
	// surface request-scoped ABAC attributes.
	EvalRule(ctx context.Context, rule string, v *auth.Viewer, obj any) (bool, error)
}

// DenyAll rejects everything; useful as the zero value before main.go wires
// a real enforcer, so the directive runners fail closed.
type DenyAll struct{}

func (DenyAll) HasRole(context.Context, *auth.Viewer, string) bool { return false }
func (DenyAll) EvalRule(context.Context, string, *auth.Viewer, any) (bool, error) {
	return false, nil
}
`, in.ModulePath), "\n")
	return os.WriteFile(filepath.Join(dir, "enforcer.go"), []byte(body), 0644)
}

func writeDirectiveRunners(in DirectiveGenInput) error {
	dir := filepath.Join(in.ServerDir, "graph", "directive")
	if err := os.MkdirAll(dir, 0755); err != nil {
		return err
	}
	body := strings.TrimLeft(fmt.Sprintf(`
// Code generated by grpc-gen. DO NOT EDIT.
// Runners that gqlgen invokes for the @auth and @policy schema directives.
// gqlgen.yml binds the generated DirectiveRoot.Auth / DirectiveRoot.Policy
// fields to NewAuth / NewPolicy on this package.

package directive

import (
	"context"

	"github.com/99designs/gqlgen/graphql"

	"%s/src/server/graph/auth"
	"%s/src/server/graph/policy"
)

// Bindings is the runtime config the runners read each request. main.go
// constructs it once and stuffs it into ctx (or passes it via closure).
type Bindings struct {
	Enforcer policy.Enforcer
}

type bindingsCtxKey struct{}

// WithBindings stores b on ctx for the directives to read. main.go's HTTP
// handler calls this before passing ctx to gqlgen.
func WithBindings(ctx context.Context, b *Bindings) context.Context {
	return context.WithValue(ctx, bindingsCtxKey{}, b)
}

func bindingsFromCtx(ctx context.Context) *Bindings {
	b, _ := ctx.Value(bindingsCtxKey{}).(*Bindings)
	return b
}

// Auth implements @auth(role: String!). Returns ErrUnauthenticated when there
// is no viewer, ErrForbidden when the viewer lacks the required role.
func Auth(ctx context.Context, _ any, next graphql.Resolver, role string) (any, error) {
	v := auth.FromContext(ctx)
	if v == nil {
		return nil, policy.ErrUnauthenticated
	}
	b := bindingsFromCtx(ctx)
	if b == nil || b.Enforcer == nil {
		// Fail closed when the gateway hasn't wired an enforcer.
		return nil, policy.ErrForbidden
	}
	if !b.Enforcer.HasRole(ctx, v, role) {
		return nil, policy.ErrForbidden
	}
	return next(ctx)
}

// Policy implements @policy(rule: String!). The rule string is the key the
// enforcer uses to look up a stored expression in MongoDB and evaluate it
// against the request's bindings.
func Policy(ctx context.Context, obj any, next graphql.Resolver, rule string) (any, error) {
	v := auth.FromContext(ctx)
	b := bindingsFromCtx(ctx)
	if b == nil || b.Enforcer == nil {
		return nil, policy.ErrForbidden
	}
	ok, err := b.Enforcer.EvalRule(ctx, rule, v, obj)
	if err != nil {
		return nil, err
	}
	if !ok {
		return nil, policy.ErrForbidden
	}
	return next(ctx)
}
`, in.ModulePath, in.ModulePath), "\n")
	return os.WriteFile(filepath.Join(dir, "directive.go"), []byte(body), 0644)
}
